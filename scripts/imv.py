"""Limux image viewer appearance for imv 5 from [imv] tokens. imv reads one config
file, so this renders all of it; it sets appearance only and leaves every
behaviour and key binding at imv's defaults."""
import re
from mangobar import contrast


def render(theme):
    v, colors, font = theme['imv'], theme['colors'], theme['typography']['sans']
    c = {role: colors[v[role]].upper() for role in ('background', 'overlay_text', 'overlay_background')}
    for value in c.values():
        if not re.fullmatch(r'#[0-9A-F]{6}', value):
            raise ValueError('invalid imv colour')
    if contrast(c['overlay_text'], c['overlay_background']) < 4.5:
        raise ValueError('insufficient imv overlay contrast')
    alpha, size = v['overlay_background_alpha'], v['overlay_size']
    if type(alpha) not in (int, float) or not 0.5 <= alpha <= 1:
        raise ValueError('invalid imv overlay alpha')
    if type(size) is not int or not 8 <= size <= 24 or not re.fullmatch(r'[\w .-]+', font):
        raise ValueError('invalid imv overlay font')
    if type(v['overlay_bottom']) is not bool:
        raise ValueError('invalid imv overlay position')
    return f'''# Generated by Limux from themes/rhapsody.toml ([imv]). Do not edit;
# scripts/activate-imv.py owns this file. Appearance only: imv's default keys apply.
[options]
background = {c['background'][1:]}
overlay = false
overlay_font = {font}:{size}
overlay_text_color = {c['overlay_text'][1:]}
overlay_background_color = {c['overlay_background'][1:]}
overlay_background_alpha = {round(alpha * 255):02x}
overlay_position_bottom = {str(v['overlay_bottom']).lower()}
title_text = ${{imv_current_file##*/}}
overlay_text = "  ${{imv_current_file##*/}}  ·  ${{imv_width}} × ${{imv_height}}  ·  ${{imv_current_index}} of ${{imv_file_count}}  "
'''
