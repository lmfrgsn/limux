"""Light Rhapsody launcher; visual properties only, no configuration overrides."""
import re
from mangobar import contrast


def render(theme):
    c, s, r = theme['colors'], theme['semantics'], theme['rofi']
    for value in c.values():
        if not isinstance(value, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
            raise ValueError('invalid Rofi colour')
    for name in ('width', 'padding', 'spacing', 'radius', 'search_padding',
                 'row_padding', 'row_spacing', 'icon_size', 'selection_edge',
                 'font_size', 'heading_size', 'entry_size'):
        value = r[name]
        if type(value) is not int or not 0 < value <= (1600 if name == 'width' else 100):
            raise ValueError(f'invalid Rofi geometry: {name}')
    font = theme['typography']['sans']
    if not isinstance(font, str) or not re.fullmatch(r'[\w .-]+', font):
        raise ValueError('invalid Rofi font')
    selected, selected_ink, urgent, on_urgent = (c[s[k]] for k in
        ('list_selected', 'on_list_selected', 'urgent', 'on_urgent'))
    # Use primary ink for placeholder inside the darker recess: secondary ink
    # would have insufficient contrast there. Yellow is an indicator, not text.
    for fg, bg in ((c['text'], c['canvas']), (c['text_secondary'], c['surface']),
                   (c['text'], c['chrome']), (urgent, c['surface']), (on_urgent, urgent)):
        if contrast(fg, bg) < 4.5:
            raise ValueError('insufficient Rofi text contrast')
    return f'''/* Generated by Limux. Rofi candidate 2, preview only. */
* {{
    font: "{font} {r['font_size']}";
    background-color: transparent;
    text-color: {c['text']};
    border-color: {c['metal']};
    padding: 0px;
    margin: 0px;
    border: 0px;
    spacing: 0px;
}}
window {{
    width: {r['width']}px;
    location: center;
    anchor: center;
    fullscreen: false;
    background-color: {c['surface']};
    border: 1px;
    border-color: {c['metal']};
    border-radius: {r['radius']}px;
    padding: {r['padding']}px;
}}
mainbox {{
    children: [ textbox-heading, box-search, listview, message ];
    orientation: vertical;
    spacing: {r['spacing']}px;
}}
textbox-heading {{
    content: "APPLICATIONS";
    font: "{font} {r['heading_size']}";
    text-color: {c['text_secondary']};
    expand: false;
}}
/* Opposing edges and a darker floor suggest a shallow recess, without blur. */
box-search {{
    children: [ inputbar ];
    orientation: vertical;
    expand: false;
    background-color: {c['canvas']};
    border: 1px 0px 0px 1px;
    border-color: {c['metal']};
    border-radius: {r['radius']}px;
}}
inputbar {{
    children: [ entry ];
    orientation: horizontal;
    expand: false;
    padding: {r['search_padding']}px;
    border: 0px 1px 1px 0px;
    border-color: {c['surface']};
}}
entry {{
    font: "{font} {r['entry_size']}";
    placeholder: "Search applications";
    placeholder-color: {c['text']};
    text-color: {c['text']};
    cursor-color: {c['text']};
    cursor-width: 2px;
    vertical-align: 0.5;
    expand: true;
}}
listview {{
    lines: 7;
    columns: 1;
    layout: vertical;
    fixed-height: false;
    dynamic: true;
    expand: true;
    scrollbar: false;
    cycle: true;
    spacing: {r['row_spacing']}px;
}}
element {{
    children: [ element-icon, element-text ];
    padding: {r['row_padding']}px;
    spacing: {r['spacing']}px;
    border: 0px 0px 0px {r['selection_edge']}px;
    border-color: transparent;
    border-radius: 0px;
    background-color: transparent;
    text-color: {c['text']};
    cursor: pointer;
}}
element normal.normal, element alternate.normal, element normal.active, element alternate.active {{
    background-color: transparent;
    text-color: {c['text']};
}}
element selected.normal, element selected.active {{
    background-color: {c['chrome']};
    border-color: {selected};
    text-color: {selected_ink};
}}
element normal.urgent, element alternate.urgent {{
    text-color: {urgent};
}}
element selected.urgent {{
    background-color: {urgent};
    border-color: {urgent};
    text-color: {on_urgent};
}}
element-icon {{
    size: {r['icon_size']}px;
    expand: false;
    vertical-align: 0.5;
}}
element-text {{
    expand: true;
    vertical-align: 0.5;
    text-color: inherit;
    highlight: bold;
}}
message {{
    expand: false;
    padding: {r['row_padding']}px;
}}
textbox {{
    text-color: {c['text_secondary']};
}}
'''
