"""Render Mangobar 0.2.2 CSS from semantic theme tokens."""
import re


def render(theme):
    colors = theme['colors']
    for key in ('canvas', 'surface', 'chrome', 'accent', 'text', 'text_secondary', 'text_quiet', 'urgent', 'on_urgent'):
        if not isinstance(colors[key], str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', colors[key]):
            raise ValueError(f'invalid color: {key}')
    typography, geometry = theme['typography'], theme['geometry']
    font = typography['sans']
    if not isinstance(font, str) or not re.fullmatch(r'[\w .-]+', font):
        raise ValueError('invalid font family')
    size, spacing, radius = typography['size'], geometry['spacing'], geometry['radius']
    if any(type(n) is not int or n < 0 or n > 100 for n in (size, spacing, radius)) or not size:
        raise ValueError('invalid size or geometry')
    c = colors
    # All colors are direct theme tokens; active text is chosen from the palette.
    def luminance(hexcolor):
        rgb = [int(hexcolor[i:i+2], 16) / 255 for i in (1, 3, 5)]
        linear = [x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4 for x in rgb]
        return sum(a*b for a, b in zip(linear, (.2126, .7152, .0722)))
    def contrast(a, b):
        a, b = sorted((luminance(a), luminance(b)))
        return (b + .05) / (a + .05)
    active_text = max((c['text'], c['surface']), key=lambda x: contrast(x, c['accent']))
    return f'''/* Generated by Limux; edit the theme tokens instead. */
* {{ font-family: "{font}"; font-size: {size}px; font-weight: 500; color: {c['text']}; background: {c['chrome']}; padding: 0px {spacing}px; margin: 0px; border-radius: 0px; }}
#bar {{ background: {c['chrome']}; padding: 0px; margin: 0px; }}
#bar.sel {{ background: {c['chrome']}; }}
#tags {{ padding: 0px {spacing}px; margin: 0px 1px; min-width: 25px; }}
#tags.empty {{ color: {c['text_quiet']}; background: {c['chrome']}; }}
#tags.occupied {{ color: {c['text']}; background: {c['chrome']}; }}
#tags.active {{ color: {active_text}; background: {c['accent']}; }}
#tags.urgent {{ color: {c['on_urgent']}; background: {c['urgent']}; }}
#tags:hover {{ color: {c['text']}; background: {c['surface']}; }}
#layout {{ color: {c['text_secondary']}; background: {c['chrome']}; padding: 0px {spacing}px; margin: 0px 5px; }}
#title {{ color: {c['text_secondary']}; }}
#clock {{ color: {c['text']}; }}
#battery {{ color: {c['text']}; }}
#volume {{ color: {c['text']}; }}
#custom-wifi {{ color: {c['text']}; background: {c['chrome']}; }}
#tray {{ padding: 0px {spacing}px; }}
menu {{ background-color: {c['surface']}; border-color: {c['accent']}; border-radius: {radius}px; font-size: {size}px; }}
menuitem {{ color: {c['text']}; }}
menuitem:hover {{ color: {c['text']}; background-color: {c['canvas']}; }}
'''
