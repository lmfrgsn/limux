"""Render Mangobar's native CSS subset; colours come only from theme tokens."""
import re


def luminance(color):
    rgb = [int(color[i:i+2], 16) / 255 for i in (1, 3, 5)]
    linear = [v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in rgb]
    return sum(v * w for v, w in zip(linear, (.2126, .7152, .0722)))


def contrast(a, b):
    low, high = sorted((luminance(a), luminance(b)))
    return (high + .05) / (low + .05)


def render(theme):
    c = theme['colors']
    for key in ('canvas', 'surface', 'chrome', 'accent', 'text', 'dark_terminal',
                'metal', 'text_secondary', 'text_quiet', 'signal_yellow',
                'signal_green', 'signal_red', 'signal_ink'):
        if not isinstance(c[key], str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', c[key]):
            raise ValueError(f'invalid color: {key}')
    s = {key: c[theme['semantics'][key]] for key in
         ('emphasis', 'selected', 'on_selected', 'success', 'on_success', 'urgent', 'on_urgent')}
    for state in ('selected', 'success', 'urgent'):
        if contrast(s[state], s['on_' + state]) < 4.5:
            raise ValueError(f'insufficient {state} text contrast')
    for fg, bg in (('text', 'surface'), ('text_secondary', 'surface'),
                   ('text_quiet', 'chrome'), ('text', 'canvas')):
        if contrast(c[fg], c[bg]) < 4.5:
            raise ValueError(f'insufficient {fg}/{bg} contrast')
    typography, geometry, bar = theme['typography'], theme['geometry'], theme['mangobar']
    font = typography['sans']
    if not isinstance(font, str) or not re.fullmatch(r'[\w .-]+', font):
        raise ValueError('invalid font family')
    size, spacing, radius = typography['size'], geometry['spacing'], geometry['radius']
    metrics = (size, spacing, radius, *bar.values())
    if any(type(n) is not int or n < 0 or n > 100 for n in metrics) or not size:
        raise ValueError('invalid size or geometry')
    weight = typography['weight']
    if type(weight) is not int or weight not in range(100, 1000, 100):
        raise ValueError('invalid font weight')
    # Native hover resolution overlays global + base + hover onto each state.
    # NO global/base tag colours: even inherited colours would erase selection.
    # Geometry-only hover preserves both yellow selection and red urgency.
    return f'''/* Generated by Limux; candidate 2, not permanently applied. */
* {{ font-family: "{font}"; font-size: {size}px; font-weight: {weight}; padding: 0px {spacing}px; margin: 0px; border-radius: 0px; }}
#bar {{ background: {c['surface']}; padding: 0px; margin: 0px; }}
#bar.sel {{ background: {c['surface']}; }}
#tags {{ padding: 0px {bar['workspace_padding']}px; margin: 0px {bar['workspace_gap']}px; min-width: {bar['workspace_min_width']}px; border-radius: {bar['control_radius']}px; }}
#tags.empty {{ color: {c['text_quiet']}; background: {c['chrome']}; }}
#tags.inactive {{ color: {c['text_quiet']}; background: {c['chrome']}; }}
#tags.occupied {{ color: {c['text']}; background: {c['canvas']}; }}
#tags.active {{ color: {s['on_selected']}; background: {s['selected']}; }}
#tags.urgent {{ color: {s['on_urgent']}; background: {s['urgent']}; }}
#tags:hover {{ border-radius: {bar['hover_radius']}px; }}
#layout {{ color: {c['text_secondary']}; background: {c['chrome']}; margin: 0px {bar['group_gap']}px; border-radius: {bar['control_radius']}px; }}
#title {{ color: {c['text_secondary']}; background: {c['surface']}; }}
#clock {{ color: {c['text']}; background: {c['surface']}; }}
#battery {{ color: {c['text_secondary']}; background: {c['surface']}; }}
#volume {{ color: {c['text_secondary']}; background: {c['surface']}; }}
#custom-wifi {{ color: {c['text_secondary']}; background: {c['surface']}; }}
#tray {{ color: {c['text']}; background: {c['surface']}; }}
#overview {{ color: {c['text']}; background: {c['chrome']}; }}
menu {{ background-color: {c['surface']}; border-color: {c['metal']}; border-radius: {radius}px; font-size: {size}px; }}
menuitem {{ color: {c['text']}; }}
menuitem:hover {{ color: {c['text']}; background-color: {c['canvas']}; }}
'''


def render_quiet(theme):
    """Approved inset Quiet Workspace Strip for the isolated Mangobar 0.2.2 build."""
    render(theme)  # Reuse complete token and contrast validation.
    c = theme['colors']
    q = theme['mangobar_candidate']
    semantics = theme['semantics']
    accent = c[semantics['workspace_active']]
    active_ink = c[semantics['on_workspace_active']]
    if not re.fullmatch(r'#[0-9a-fA-F]{6}', accent):
        raise ValueError('invalid Quiet Workspace Strip accent')
    if contrast(accent, active_ink) < 4.5:
        raise ValueError('insufficient active workspace contrast')
    for key in ('workspace_padding', 'workspace_gap', 'active_radius', 'active_inset'):
        value = q[key]
        if type(value) is not int or not 0 <= value <= 20:
            raise ValueError(f'invalid {key}')
    if type(q['bar_height']) is not int or not 20 <= q['bar_height'] <= 40:
        raise ValueError('invalid candidate bar height')
    if q['active_inset'] * 3 > q['bar_height']:
        raise ValueError('active inset exceeds renderer limit')
    font, size, weight = (theme['typography'][k] for k in ('sans', 'size', 'weight'))
    # The native bar forces workspace minimum width to bar height after loading
    # CSS. A #tags min-width would then be reapplied from the hover overlay and
    # shrink the hotspot. Keep every state and hover free of min-width.
    return f'''/* Limux Quiet Workspace Strip: isolated Mangobar 0.2.2 preview. */
* {{ font-family: "{font}"; font-size: {size}px; font-weight: {weight}; padding: 0px 8px; margin: 0px; }}
#bar {{ background: {c['surface']}; padding: 0px; margin: 0px; }}
#bar.sel {{ background: {c['surface']}; }}
#tags {{ padding: 0px {q['workspace_padding']}px; margin: 0px {q['workspace_gap']}px; }}
#tags.empty {{ color: {c['text_quiet']}; background: none; }}
#tags.inactive {{ color: {c['text_quiet']}; background: none; }}
#tags.occupied {{ color: {c['text_secondary']}; background: none; }}
#tags.active {{ color: {active_ink}; background: {accent}; border-radius: {q['active_radius']}px; background-inset: {q['active_inset']}px; }}
#tags.urgent {{ color: {c['signal_red']}; background: none; }}
#title {{ color: {c['text_quiet']}; background: {c['surface']}; margin-left: 12px; }}
#clock {{ color: {c['text']}; background: {c['surface']}; }}
#battery {{ color: {c['text_secondary']}; background: {c['surface']}; }}
#volume {{ color: {c['text_secondary']}; background: {c['surface']}; }}
#custom-wifi {{ color: {c['text_secondary']}; background: {c['surface']}; }}
#tray {{ color: {c['text']}; background: {c['surface']}; }}
#overview {{ color: {c['text']}; background: {c['surface']}; }}
menu {{ background-color: {c['surface']}; border-color: {c['metal']}; border-radius: {theme['geometry']['radius']}px; font-size: {size}px; }}
menuitem {{ color: {c['text']}; }}
menuitem:hover {{ color: {c['text']}; background-color: {c['canvas']}; }}
'''
