"""Mako 1.11 appearance adapter. No anchor, timeouts, visibility, actions or bindings."""
import re
from mangobar import contrast

COLORS = ('surface', 'text', 'secondary', 'label', 'edge', 'urgent', 'progress')
METRICS = (('border', 0, 4), ('radius', 0, 16), ('padding_vertical', 0, 32),
           ('padding_horizontal', 0, 32), ('width', 200, 600), ('margin', 0, 48), ('label_tracking', 0, 2000))
# Behaviour stays in the user's config; the fragment must never set these.
FUNCTIONAL = ('anchor', 'default-timeout', 'ignore-timeout', 'max-visible', 'layer', 'output', 'sort',
              'max-history', 'history', 'group-by', 'invisible', 'actions', 'on-button-left',
              'on-button-middle', 'on-button-right', 'on-touch', 'on-notify', 'include')


def palette(theme):
    m, colors = theme['mako'], theme['colors']
    c = {role: colors[m[role]].upper() for role in COLORS}
    for value in c.values():
        if not re.fullmatch(r'#[0-9A-F]{6}', value):
            raise ValueError('invalid Mako colour')
    for ink in ('text', 'secondary', 'label', 'urgent'):
        if contrast(c[ink], c['surface']) < 4.5:
            raise ValueError(f'insufficient Mako contrast: {ink}')
    if contrast(c['text'], c['progress']) < 4.5:
        raise ValueError('insufficient Mako contrast over progress')
    return c


def render(theme):
    m, c, t = theme['mako'], palette(theme), theme['typography']
    for key, low, high in METRICS:
        if type(m[key]) is not int or not low <= m[key] <= high:
            raise ValueError(f'invalid Mako {key}')
    if not re.fullmatch(r'[\w .-]+', t['sans']) or type(t['ui_size']) is not int:
        raise ValueError('invalid Mako typography')

    def label(colour, text='%a'):
        return (f'<span size="small" weight="500" foreground="{colour}" text_transform="uppercase" '
                f'letter_spacing="{m["label_tracking"]}">{text}</span>')

    body = f'<span foreground="{c["secondary"]}">%b</span>'
    summary = '<b>%s</b>'
    lines = [
        '# Generated by Limux from themes/rhapsody.toml ([mako]). Do not edit;',
        '# scripts/activate-mako.py owns this file. Appearance only.',
        f'font={t["sans"]} {t["ui_size"]}',
        f'background-color={c["surface"]}',
        f'text-color={c["text"]}',
        f'border-color={c["edge"]}',
        f'border-size={m["border"]}',
        f'border-radius={m["radius"]}',
        f'padding={m["padding_vertical"]},{m["padding_horizontal"]}',
        f'width={m["width"]}',
        f'margin={m["margin"]}',
        'icons=0',
        'markup=1',
        f'progress-color=over {c["progress"]}',
        f'format={label(c["label"])}\\n{summary}\\n{body}',
        '',
        '[grouped]',
        f'format={label(c["label"], "%a  ·  %g")}\\n{summary}\\n{body}',
        '',
        '[urgency=low]',
        f'format={label(c["label"])}\\n<span foreground="{c["secondary"]}">%s</span>\\n{body}',
        '',
        '[urgency=critical]',
        f'border-color={c["urgent"]}',
        f'format={label(c["urgent"])}\\n{summary}\\n{body}',
    ]
    text = '\n'.join(lines) + '\n'
    for line in text.splitlines():
        if line.split('=', 1)[0] in FUNCTIONAL:
            raise ValueError(f'Mako fragment must not set behaviour: {line}')
    return text
