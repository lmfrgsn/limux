"""Limux lock screen appearance for hyprlock 0.9 from [lock] tokens. Behaviour
(grace, input handling, authentication) stays in the hand-maintained hyprlock.conf,
which sources this file; idle timings live in hypridle.conf."""
import re
from mangobar import contrast

COLORS = ('ground', 'time', 'date', 'labels', 'placeholder', 'field', 'field_edge', 'checking', 'fail', 'dots')
METRICS = (('time_size', 32, 200), ('time_weight', 100, 900), ('date_size', 8, 48), ('note_size', 8, 32),
           ('field_width', 120, 600), ('field_height', 24, 80), ('field_edge_width', 1, 4),
           ('field_radius', 0, 20), ('dot_size', 4, 20), ('dot_gap', 2, 24), ('motion', 1, 10), ('stack_raise', 0, 400),
           ('date_gap', 0, 80), ('field_gap', 0, 160), ('note_gap', 0, 60), ('user_inset', 0, 200))
CAPS = '/sys/class/leds/input*::capslock/brightness'


def palette(theme):
    k, colors = theme['lock'], theme['colors']
    c = {role: colors[k[role]].upper() for role in COLORS}
    for value in c.values():
        if not re.fullmatch(r'#[0-9A-F]{6}', value):
            raise ValueError('invalid lock colour')
    for ink, ground in (('time', 'ground'), ('date', 'ground'), ('labels', 'ground'), ('placeholder', 'field'),
                        ('dots', 'field'), ('fail', 'field')):
        if contrast(c[ink], c[ground]) < 4.5:
            raise ValueError(f'insufficient lock contrast: {ink} on {ground}')
    return c


def rgb(value):
    return f'rgb({value[1:]})'


def render(theme):
    k, c, font = theme['lock'], palette(theme), theme['typography']['sans']
    for key, low, high in METRICS:
        if type(k[key]) is not int or not low <= k[key] <= high:
            raise ValueError(f'invalid lock {key}')
    if not re.fullmatch(r'[\w .-]+', font):
        raise ValueError('invalid lock font')
    # hyprlock positions are offsets from the display centre, y upwards.
    date_text = 20  # line box of the date
    note_text = 18
    height = k['time_size'] + k['date_gap'] + date_text + k['field_gap'] + k['field_height'] + k['note_gap'] + note_text
    top = k['stack_raise'] + height // 2
    time_y = top - k['time_size'] // 2
    date_y = top - k['time_size'] - k['date_gap'] - date_text // 2
    field_y = date_y - date_text // 2 - k['field_gap'] - k['field_height'] // 2
    note_y = field_y - k['field_height'] // 2 - k['note_gap'] - note_text // 2
    dots = round(k['dot_size'] / k['field_height'], 2)
    # hyprlock's dot spacing is the gap as a fraction of the dot size.
    spacing = round(min(1, k['dot_gap'] / k['dot_size']), 2)

    def label(text, size, colour, y, halign='center', valign='center'):
        return (f'label {{\n    text = {text}\n    color = {rgb(colour)}\n    font_size = {size}\n'
                f'    font_family = {font}\n    position = 0, {y}\n    halign = {halign}\n    valign = {valign}\n}}\n')

    return f'''# Generated by Limux from themes/rhapsody.toml ([lock]). Do not edit;
# scripts/activate-lock.py owns this file. Sourced by hyprlock.conf.
background {{
    color = {rgb(c['ground'])}
}}

animations {{
    enabled = true
    bezier = limux, 0.2, 0, 0, 1
    animation = fadeIn, 1, {k['motion']}, limux
    animation = fadeOut, 1, {k['motion']}, limux
    animation = inputFieldColors, 1, {k['motion']}, limux
    animation = inputFieldFade, 1, {k['motion']}, limux
    animation = inputFieldDots, 1, {k['motion']}, limux
}}

''' + label(f'<span font_weight="{k["time_weight"]}">$TIME</span>', k['time_size'], c['time'], time_y) + '\n' \
        + label('cmd[update:60000] date "+%A %-d %B"', k['date_size'], c['date'], date_y) + '\n' + f'''input-field {{
    size = {k['field_width']}, {k['field_height']}
    position = 0, {field_y}
    halign = center
    valign = center
    outline_thickness = {k['field_edge_width']}
    rounding = {k['field_radius']}
    outer_color = {rgb(c['field_edge'])}
    inner_color = {rgb(c['field'])}
    font_color = {rgb(c['dots'])}
    font_family = {font}
    check_color = {rgb(c['checking'])}
    fail_color = {rgb(c['fail'])}
    capslock_color = -1
    numlock_color = -1
    bothlock_color = -1
    # hyprlang starts a comment at '#'; '##' is a literal '#'.
    placeholder_text = <span foreground="##{c['placeholder'][1:]}">Password</span>
    fail_text = <span foreground="##{c['fail'][1:]}">Wrong password</span>
    dots_size = {dots}
    dots_spacing = {spacing}
    dots_center = true
    fade_on_empty = false
    shadow_passes = 0
}}

''' + label(f'cmd[update:500] grep -qs 1 {CAPS} && echo "Caps Lock is on"', k['note_size'], c['labels'], note_y) \
        + '\n' + label('$USER', k['note_size'], c['labels'], k['user_inset'], valign='bottom')
