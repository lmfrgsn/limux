"""Limux system monitor appearance for btop 1.4 from [btop] tokens: a generated
.theme file and the few appearance keys btop keeps in btop.conf. Behaviour,
boxes, sorting and keys stay btop's own."""
import re
from foot import palette
from mangobar import contrast

NAME = 'limux-rhapsody'
LOAD = ('cpu', 'temp', 'used', 'process')
CALM = ('free', 'cached', 'available', 'download', 'upload')


def colors(theme):
    c = palette(theme)
    for name, (source, destination, amount) in theme['btop']['blends'].items():
        if name in c or type(amount) not in (int, float) or not 0 <= amount <= 1:
            raise ValueError('invalid btop blend')
        a, b = c[source], c[destination]
        c[name] = '#' + ''.join(f'{round(int(a[i:i+2], 16) * (1-amount) + int(b[i:i+2], 16) * amount):02X}' for i in (1, 3, 5))
    return c


def roles(theme):
    b, c = theme['btop'], colors(theme)
    pick = {role: c[b[role]].upper() for role in (
        'background', 'text', 'title', 'keys', 'quiet', 'selected', 'on_selected', 'hairline', 'inactive')}
    for ramp in ('load', 'calm'):
        if len(b[ramp]) != 3:
            raise ValueError(f'btop {ramp} ramp needs start, middle and end')
        pick[ramp] = [c[name].upper() for name in b[ramp]]
    for value in [v for v in pick.values() if isinstance(v, str)] + pick['load'] + pick['calm']:
        if not re.fullmatch(r'#[0-9A-F]{6}', value):
            raise ValueError('invalid btop colour')
    for role in ('text', 'title', 'keys', 'quiet', *[f'load{i}' for i in range(3)], 'calm2'):
        ink = pick[role[:-1]][int(role[-1])] if role[-1].isdigit() else pick[role]
        if contrast(ink, pick['background']) < 4.5:
            raise ValueError(f'insufficient btop contrast: {role}')
    if contrast(pick['on_selected'], pick['selected']) < 4.5:
        raise ValueError('insufficient btop selection contrast')
    return pick


def render(theme):
    r = roles(theme)
    t = {'main_bg': r['background'], 'main_fg': r['text'], 'title': r['title'], 'hi_fg': r['keys'],
         'selected_bg': r['selected'], 'selected_fg': r['on_selected'], 'inactive_fg': r['inactive'],
         'graph_text': r['quiet'], 'meter_bg': r['hairline'], 'proc_misc': r['quiet'],
         'cpu_box': r['hairline'], 'mem_box': r['hairline'], 'net_box': r['hairline'],
         'proc_box': r['hairline'], 'div_line': r['hairline']}
    for names, ramp in ((LOAD, r['load']), (CALM, r['calm'])):
        for name in names:
            t.update({f'{name}_start': ramp[0], f'{name}_mid': ramp[1], f'{name}_end': ramp[2]})
    return ('# Generated by Limux from themes/rhapsody.toml ([btop]). Do not edit;\n'
            '# scripts/activate-btop.py owns this file.\n'
            + ''.join(f'theme[{key}]="{value}"\n' for key, value in t.items()))


def settings(theme):
    """The appearance keys Limux owns in btop.conf, in btop's own value syntax."""
    rounded = theme['btop']['rounded_corners']
    if type(rounded) is not bool:
        raise ValueError('invalid btop rounded_corners')
    return {'color_theme': f'"{NAME}"', 'theme_background': 'false',
            'truecolor': 'true', 'rounded_corners': str(rounded).lower()}
