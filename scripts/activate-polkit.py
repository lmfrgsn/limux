#!/usr/bin/env python3
"""Guarded polkit authentication agent: polkit-gnome with the Limux prompt theme.

  activate  install the Limux-Dialog theme, add the autostart, (re)start the agent
  verify    pinned theme, one agent running and exactly one autostart line
  rollback  stop the agent, remove the autostart and the theme

The agent alone runs with GTK_THEME=Limux-Dialog: adw-gtk3 plus the Rhapsody card,
generated from the tokens (scripts/gtk.py). Run from Foot in the desktop session;
the package is installed separately.
"""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import tomllib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'scripts'))
from gtk import DIALOG_THEME, render_dialog_css, render_dialog_index  # noqa: E402

HOME = Path.home()
CONFIG = HOME/'.config/mango/config.conf'
AGENT = '/usr/lib/polkit-gnome/polkit-gnome-authentication-agent-1'
AUTOSTART = f'exec_once=env GTK_THEME={DIALOG_THEME} {AGENT}'
PREVIOUS = (f'exec_once={AGENT}',)  # earlier Limux autostarts, replaced in place
NAME = 'polkit-gnome-au'  # the kernel's 15-character process name
MANIFEST = ROOT/'themes/recovery/polkit.json'
THEME = HOME/'.local/share/themes'/DIALOG_THEME


def theme_files():
    """The prompt theme's files, checked against the approval pin."""
    theme = tomllib.loads((ROOT/'themes/rhapsody.toml').read_text())
    files = {THEME/'gtk-3.0/gtk.css': render_dialog_css(theme).encode(),
             THEME/'index.theme': render_dialog_index(theme).encode()}
    pins = json.loads(MANIFEST.read_text())['files']
    for path, data in files.items():
        if hashlib.sha256(data).hexdigest() != pins[str(path.relative_to(THEME))]:
            raise RuntimeError(f'{path.name} differs from the approved pin')
    return files


def run(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True, timeout=12)


def agent_pids():
    found = subprocess.run(['pgrep', '-u', str(os.getuid()), '-x', NAME], capture_output=True, text=True)
    return [int(pid) for pid in found.stdout.split()]


def configured(text):
    lines = [line.strip() for line in text.splitlines() if not line.lstrip().startswith('#')]
    agents = [line for line in lines if line.startswith('exec') and 'polkit' in line]
    if agents and agents != [AUTOSTART] and not (len(agents) == 1 and agents[0] in PREVIOUS):
        raise RuntimeError('another polkit agent autostart exists; inspect the MangoWM config')
    return agents == [AUTOSTART]


def write_config(before, after):
    with tempfile.NamedTemporaryFile(mode='w', dir=CONFIG.parent, prefix='.polkit-', delete=False) as stream:
        stream.write(after)
        staged = Path(stream.name)
    try:
        run('mango', '-p', '-c', str(staged))
        os.chmod(staged, CONFIG.stat().st_mode & 0o777)
        os.replace(staged, CONFIG)
    finally:
        staged.unlink(missing_ok=True)
    try:
        run('mmsg', 'dispatch', 'reload_config')
        run('mmsg', 'get', 'version')
    except Exception:
        CONFIG.write_text(before)
        raise


def themed(pid):
    try:
        return f'GTK_THEME={DIALOG_THEME}'.encode() in Path(f'/proc/{pid}/environ').read_bytes().split(b'\0')
    except OSError:
        return False


def activate():
    if not os.access(AGENT, os.X_OK):
        raise RuntimeError('polkit-gnome is not installed; run: sudo pacman -S --needed polkit-gnome')
    run('mmsg', 'get', 'version')
    files = theme_files()
    for path in files:
        if path.exists() and path.read_bytes() != files[path] and \
                not path.read_bytes().startswith(b'/* Generated by Limux') and path.name == 'gtk.css':
            raise RuntimeError(f'{path} was not written by Limux; refusing to overwrite')
    before = CONFIG.read_text()
    pids = agent_pids()
    if configured(before) and len(pids) == 1 and themed(pids[0]) and \
            all(p.exists() and p.read_bytes() == d for p, d in files.items()):
        print('Polkit agent already active.')
        return
    previous = [line for line in before.splitlines() if line.strip() in PREVIOUS]
    if pids and not configured(before) and not previous:
        raise RuntimeError('a polkit agent is already running outside Limux; stop it first')
    for path, data in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    if not configured(before):
        lines = [line for line in before.splitlines(keepends=True) if line.strip() not in PREVIOUS]
        last = max(i for i, line in enumerate(lines) if line.startswith('exec_once='))
        lines.insert(last + 1, AUTOSTART + '\n')
        write_config(before, ''.join(lines))
    try:
        for pid in agent_pids():
            if not themed(pid):
                os.kill(pid, 15)
        time.sleep(0.5)
        if not agent_pids():
            subprocess.Popen(['setsid', '-f', 'env', f'GTK_THEME={DIALOG_THEME}', AGENT],
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            time.sleep(1.5)
        if len(agent_pids()) != 1:
            raise RuntimeError('the polkit agent did not start')
    except BaseException:
        write_config(CONFIG.read_text(), before)
        raise
    print('Polkit agent active: admin actions now ask for your password in a dialog.')


def rollback():
    for pid in agent_pids():
        os.kill(pid, 15)
    before = CONFIG.read_text()
    configured(before)
    if any(line.strip() in (AUTOSTART, *PREVIOUS) for line in before.splitlines()):
        run('mmsg', 'get', 'version')
        write_config(before, ''.join(line for line in before.splitlines(keepends=True)
                                     if line.strip() not in (AUTOSTART, *PREVIOUS)))
    for name in ('gtk-3.0/gtk.css', 'index.theme'):
        (THEME/name).unlink(missing_ok=True)
    for folder in (THEME/'gtk-3.0', THEME):
        try:
            folder.rmdir()
        except OSError:
            pass
    print('Polkit agent stopped; its autostart and prompt theme removed. The package stays installed.')


def verify():
    files = theme_files()
    installed = all(p.exists() and p.read_bytes() == d for p, d in files.items())
    pids = agent_pids()
    state = configured(CONFIG.read_text()) and installed and all(themed(pid) for pid in pids), len(pids)
    summary = 'active' if state == (True, 1) else 'not active' if state == (False, 0) else f'mixed: autostart={state[0]}, agents={state[1]}'
    print(f'Polkit agent {summary}.')
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('action', choices=['activate', 'verify', 'rollback'])
    action = parser.parse_args().action
    if action == 'verify':
        if verify() != 'active':
            raise SystemExit('Polkit agent is not fully active.')
        return
    with (Path(os.environ['XDG_RUNTIME_DIR'])/'limux-polkit-activation.lock').open('w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        activate() if action == 'activate' else rollback()


if __name__ == '__main__':
    try:
        main()
    except (OSError, RuntimeError, ValueError, subprocess.SubprocessError) as exc:
        raise SystemExit(f'Polkit agent: {exc}')
